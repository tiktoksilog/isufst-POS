    public SalesReportFrame() {
        initComponents();

        salesModel = readOnlyModel("Receipt No.", "Date / Time", "Cashier", "Total", "Cash", "Change");
        itemsModel = readOnlyModel("Product", "Unit Price", "Qty", "Subtotal");
        tblSales.setModel(salesModel);
        tblItems.setModel(itemsModel);
        tblSales.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
        tblSales.getSelectionModel().addListSelectionListener(e -> {
            if (!e.getValueIsAdjusting() && controller != null) {
                controller.loadItems();
            }
        });

        setSize(900, 620);
        setLocationRelativeTo(null);

        controller = new SalesController(this);
    }

    private static DefaultTableModel readOnlyModel(String... columns) {
        return new DefaultTableModel(columns, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
    }

    // ---------- methods used by the controller ----------

    public String getDateText() {
        return txtDate.getText().trim();
    }

    public void setDateText(String text) {
        txtDate.setText(text);
    }

    public void showSales(List<Sale> sales) {
        salesModel.setRowCount(0);
        for (Sale s : sales) {
            salesModel.addRow(new Object[]{
                String.format("%06d", s.getSaleId()),
                Formatter.dateTime(s.getSaleDate()),
                s.getCashierName(),
                Formatter.money(s.getTotalAmount()),
                Formatter.money(s.getAmountPaid()),
                Formatter.money(s.getChangeAmount())
            });
        }
    }

    public void showItems(List<SaleItem> items) {
        itemsModel.setRowCount(0);
        for (SaleItem i : items) {
            itemsModel.addRow(new Object[]{
                i.getProductName(),
                Formatter.money(i.getUnitPrice()),
                i.getQuantity(),
                Formatter.money(i.getSubtotal())
            });
        }
    }

    public int getSelectedSaleIndex() {
        return tblSales.getSelectedRow();
    }

    public void setSummary(int count, BigDecimal total) {
        lblSummary.setText("Transactions: " + count + "   |   Total Sales: " + Formatter.peso(total));
    }

    public void showError(String message) {
        JOptionPane.showMessageDialog(this, message, "Sales Report", JOptionPane.ERROR_MESSAGE);
    }

